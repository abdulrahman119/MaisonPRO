#!/usr/bin/env node
/* =========================================================
   MaisonPRO · static build (لا مكتبات، لا خطوات تثبيت)

   node tools/build.mjs

   1) ينسخ الموقع إلى dist/ (الملفات العامة فقط)
   2) يوحّد كل الروابط المطلقة (canonical / hreflang / JSON-LD /
      og:image / sitemap / robots) مع عنوان النشر الفعلي
   3) يولّد dist/assets/js/runtime.js من متغيرات البيئة
   4) في وضع العرض التجريبي يمنع فهرسة الإعلانات الوهمية

   متغيرات البيئة (كلها اختيارية):
     SITE_URL          عنوان الموقع النهائي، مثلاً https://maisonpro.dj
                       (على Netlify يُقرأ URL تلقائياً، وعلى Vercel
                        VERCEL_PROJECT_PRODUCTION_URL)
     DEMO_MODE         1 = افتراضي (شريط تنبيه + noindex) | 0 = إطلاق رسمي
     FORMS_PROVIDER    none | formspree | supabase
     FORMS_ENDPOINT    رابط استقبال طلبات «أضف عقارك»
     FORMS_API_KEY     مفتاح Supabase العام (anon) فقط — ليس مفتاحاً سرياً
   ========================================================= */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist');
const env = process.env;

/* ---------- 1. الإعدادات ---------- */
function normalizeUrl(u) {
  u = String(u || '').trim();
  if (!u) return 'https://maisonpro.dj';
  if (!/^https?:\/\//i.test(u)) u = 'https://' + u;
  return u.replace(/\/+$/, '');
}
const SITE_URL = normalizeUrl(
  env.SITE_URL ||
  env.URL ||
  env.DEPLOY_PRIME_URL ||
  (env.VERCEL_PROJECT_PRODUCTION_URL ? 'https://' + env.VERCEL_PROJECT_PRODUCTION_URL : '') ||
  'https://maisonpro.dj'
);
const demoMode = !['0', 'false', 'no', 'off'].includes(String(env.DEMO_MODE ?? '1').toLowerCase());
const provider = String(env.FORMS_PROVIDER || 'none').trim();
const endpoint = String(env.FORMS_ENDPOINT || '').trim();
const apiKey = String(env.FORMS_API_KEY || '').trim();

/* ---------- 2. نسخ الملفات العامة فقط ---------- */
const FILES = ['index.html', 'privacy.html', 'terms.html', '404.html', 'robots.txt', 'sitemap.xml'];
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
fs.cpSync(path.join(ROOT, 'assets'), path.join(OUT, 'assets'), { recursive: true });
for (const f of FILES) fs.copyFileSync(path.join(ROOT, f), path.join(OUT, f));

const read = (f) => fs.readFileSync(path.join(OUT, f), 'utf8');
const write = (f, s) => fs.writeFileSync(path.join(OUT, f), s);

/* ---------- 3. توحيد عنوان الموقع ---------- */
const OLD_DOMAINS = [
  /https:\/\/abdulrahman119\.github\.io\/MaisonPRO/g,
  /https:\/\/maisonpro\.dj/g
];
const patchUrls = (s) => OLD_DOMAINS.reduce((acc, re) => acc.replace(re, SITE_URL), s);
for (const f of FILES) write(f, patchUrls(read(f)));

/* ---------- 4. وضع العرض التجريبي ---------- */
if (demoMode) {
  write('index.html', read('index.html').replace(
    /name="robots" content="[^"]*"/,
    'name="robots" content="noindex,follow"'
  ));
}

/* ---------- 5. إعدادات وقت التشغيل ---------- */
write(path.join('assets', 'js', 'runtime.js'),
  '/* generated by tools/build.mjs — do not edit */\n' +
  'window.MP_RUNTIME_CONFIG = ' +
  JSON.stringify({ demoMode, forms: { provider, endpoint, apiKey } }, null, 2) + ';\n'
);

/* ---------- 6. CNAME (لمن ينشر لاحقاً على GitHub Pages بدومين خاص) ---------- */
let host = '';
try { host = new URL(SITE_URL).hostname; } catch (e) { /* تجاهل */ }
if (host && !/(netlify\.app|vercel\.app|github\.io)$/i.test(host)) {
  write('CNAME', host + '\n');
}

/* ---------- تقرير البناء ---------- */
console.log('MaisonPRO build ✓');
console.log('  dist/            → جاهز للنشر');
console.log('  SITE_URL         → ' + SITE_URL);
console.log('  DEMO_MODE        → ' + (demoMode ? '1 (شريط تنبيه + noindex)' : '0 (إطلاق رسمي)'));
console.log('  FORMS_PROVIDER   → ' + (endpoint ? provider : 'none'));
console.log('  FORMS_ENDPOINT   → ' + (endpoint || 'غير مضبوط (حفظ محلي + واتساب)'));
if (!endpoint) console.log('  ⚠ اضبط FORMS_ENDPOINT في لوحة الاستضافة قبل الإطلاق — راجع LAUNCH.md');
