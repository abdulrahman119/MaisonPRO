/* ---------- runtime ---------- */
const LANGS = ['ar', 'fr', 'en'];
const LANG_LABEL = { ar: 'العربية', fr: 'Français', en: 'English' };
let LANG = 'ar';

function t(key, vars) {
  const dict = STRINGS[LANG] || STRINGS.ar;
  let s = dict[key];
  if (s === undefined) s = STRINGS.ar[key];
  if (s === undefined) return key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

const loc = (obj) => obj ? (obj[LANG] || obj.ar || obj.fr || '') : '';
const districtName = (id) => { const d = DISTRICTS.find(x => x.id === id); return d ? loc(d) : id; };
const typeName = (id) => { const x = TYPES.find(v => v.id === id); return x ? loc(x) : id; };
const amenityName = (id) => { const a = AMENITIES[id]; return a ? loc(a) : id; };

function applyLang(lang) {
  if (!LANGS.includes(lang)) lang = 'ar';
  LANG = lang;
  const rtl = lang === 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  document.body.dataset.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t(el.dataset.i18n);
    if (v !== el.dataset.i18n) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const v = t(el.dataset.i18nHtml);
    if (v !== el.dataset.i18nHtml) el.innerHTML = v;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });

  document.querySelectorAll('[data-lang]').forEach(b => {
    b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
  });
  const lbl = document.getElementById('lang-label');
  if (lbl) lbl.textContent = LANG_LABEL[lang];

  const y = document.getElementById('year');
  if (y) y.textContent = new Date().getFullYear();

  try { localStorage.setItem('mp:lang', lang); } catch (e) {}
  document.dispatchEvent(new Event('langchange'));
}

window.STRINGS = STRINGS;
window.t = t;
window.loc = loc;
window.applyLang = applyLang;
window.getLang = () => LANG;
window.districtName = districtName;
window.typeName = typeName;
window.amenityName = amenityName;
