const LANGS = ['ar', 'fr', 'en'];
const LANG_LABEL = { ar: 'العربية', fr: 'Français', en: 'English' };
let LANG = 'ar';

function t(key, vars) {
  const dict = STRINGS[LANG] || STRINGS.ar;
  let s = dict[key];
  if (s === undefined) s = STRINGS.ar[key];
  if (s === undefined) return key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

const loc = (obj) => obj ? (obj[LANG] || obj.ar || obj.fr || '') : '';
const districtName = (id) => { const d = DISTRICTS.find(x => x.id === id); return d ? loc(d) : id; };
const typeName = (id) => { const x = TYPES.find(v => v.id === id); return x ? loc(x) : id; };
const amenityName = (id) => { const a = AMENITIES[id]; return a ? loc(a) : id; };

