/* pick a language from the browser, defaulting to Arabic */
window.detectLang = function () {
  let saved = null;
  try { saved = localStorage.getItem('mp:lang'); } catch (e) {}
  if (saved) return saved;
  const list = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || 'ar'];
  for (const tag of list) {
    const k = String(tag).slice(0, 2).toLowerCase();
    if (k === 'ar' || k === 'fr' || k === 'en') return k;
  }
  return 'ar';
};
